<?php
/**
 * Renders the canonical page-builder parity fixture to a static page.
 *
 * WHY A STATIC PAGE: the layout-parity gate has to compare the SAME document
 * under the SAME CSS at the SAME viewport, and it has to do that repeatably. A
 * live page brings a tenant database, a login session, page caching and the
 * request path with it — none of which the layout depends on, all of which can
 * make a comparison fail for reasons that are not layout. This renders the
 * document through the SAME authoritative entry point the public page uses
 * (cmsBuilderRenderDocument()), inlines the same stylesheets in the same order
 * the ARK layout links them, and reproduces ARK's content shell so the theme
 * resolves the builder's layout tokens (--ikb-content-max-width,
 * --ikb-fullbleed-*) exactly where it does in production.
 *
 * The output is joined to the browser by data-node-id, so
 * tests/browser/builder-render-parity.spec.js can assert layout per node.
 *
 * Usage:
 *   php tools/builder-parity-render.php            # write the fixture page
 *   php tools/builder-parity-render.php --list     # print the node ids
 */
declare(strict_types=1);

$root = dirname(__DIR__);

ob_start();
require $root . '/bootstrap.php';
require_once BASE_PATH . '/src/helpers/module-manager.php';
foreach (['/helpers/50-builder.php', '/builder-renderers.php'] as $file) {
    if (file_exists(BASE_PATH . '/modules/cms' . $file)) {
        require_once BASE_PATH . '/modules/cms' . $file;
    }
}
ob_end_clean();

if (!function_exists('cmsBuilderRenderDocument')) {
    fwrite(STDERR, "cmsBuilderRenderDocument() unavailable — cannot render the parity fixture\n");
    exit(1);
}

require_once __DIR__ . '/lib/builder-parity-fixture.php';

$document = builderParityFixtureDocument();

// Collect the ids the fixture declares, so the spec can report a missing node
// as a missing node rather than as a geometry mismatch.
$declared = builderParityFixtureIds($document);

if (in_array('--list', $argv, true)) {
    echo implode("\n", $declared), "\n";
    exit(0);
}

$body = cmsBuilderRenderDocument($document, ['is_editor_preview' => false]);
if (trim($body) === '') {
    fwrite(STDERR, "The parity fixture rendered empty — refusing to write a blank baseline page\n");
    exit(1);
}

// Same order as storage/cms-themes/ark/layouts/public.disyl: the CMS-owned
// structural base first, then the theme, so the cascade matches production.
$cmsPublicCss = (string) file_get_contents($root . '/public/assets/cms/cms-public.css');
$themeCss = (string) file_get_contents($root . '/storage/cms-themes/ark/style.css');

$html = '<!DOCTYPE html>' . "\n"
    . '<html lang="en" class="ark-theme">' . "\n<head>\n"
    . '<meta charset="UTF-8">' . "\n"
    . '<meta name="viewport" content="width=device-width, initial-scale=1.0">' . "\n"
    . '<title>Page Builder Render Parity Fixture</title>' . "\n"
    . "<!-- Generated by tools/builder-parity-render.php — do not edit by hand. -->\n"
    . '<style>' . $cmsPublicCss . '</style>' . "\n"
    . '<style>' . $themeCss . '</style>' . "\n"
    . '</head>' . "\n<body>\n"
    // ARK's content shell. The theme publishes --ikb-content-max-width and
    // resolves --ikb-fullbleed-* on .ark-main, so without these wrappers the
    // builder's layout tokens resolve differently here than in production.
    . '<div class="ark-content-area">' . "\n"
    . '<main id="main-content" class="ark-main" tabindex="-1">' . "\n"
    . $body . "\n"
    . '</main>' . "\n</div>\n"
    . "</body>\n</html>\n";

$outDir = $root . '/tests/browser/fixtures';
if (!is_dir($outDir) && !mkdir($outDir, 0775, true) && !is_dir($outDir)) {
    fwrite(STDERR, "Could not create {$outDir}\n");
    exit(1);
}
$outPath = $outDir . '/builder-parity.html';
if (file_put_contents($outPath, $html) === false) {
    fwrite(STDERR, "Could not write {$outPath}\n");
    exit(1);
}

// Count only element markers. The rendered bundle also embeds responsive CSS
// whose selectors read [data-node-id="…"], so counting the raw string would
// report phantom nodes.
$markup = (string) preg_replace('!<style\b[^>]*>.*?</style>!is', '', $body);
preg_match_all('/data-node-id="([^"]*)"/', $markup, $m);
$renderedIds = array_values(array_filter($m[1], static fn(string $id): bool => $id !== ''));
printf(
    "parity fixture: %d declared nodes, %d rendered elements -> %s (%d bytes)\n",
    count($declared),
    count($renderedIds),
    str_replace($root . '/', '', $outPath),
    strlen($html)
);
if (count($renderedIds) !== count($declared)) {
    printf(
        "  note: not rendered -> %s\n",
        implode(', ', array_diff($declared, $renderedIds)) ?: '(none)'
    );
}
