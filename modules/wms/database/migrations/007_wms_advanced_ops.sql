CREATE TABLE IF NOT EXISTS wms_event_webhooks (
    id                INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    event_name        VARCHAR(100) NOT NULL,
    url               VARCHAR(500) NOT NULL,
    secret            VARCHAR(255) NULL DEFAULT NULL COMMENT 'HMAC secret for payload verification',
    headers           JSON NULL DEFAULT NULL COMMENT 'Custom headers as JSON object',
    retry_count       TINYINT UNSIGNED NOT NULL DEFAULT 3,
    timeout_ms        INT UNSIGNED NOT NULL DEFAULT 5000,
    is_active         TINYINT(1) NOT NULL DEFAULT 1,
    last_triggered_at DATETIME NULL DEFAULT NULL,
    last_status       VARCHAR(30) NULL DEFAULT NULL COMMENT 'success, failed',
    created_by        INT UNSIGNED NOT NULL,
    created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_wms_webhook_event (event_name),
    INDEX idx_wms_webhook_active (is_active),
    CONSTRAINT fk_wms_webhook_creator FOREIGN KEY (created_by) REFERENCES wms_users (id) ON DELETE CASCADE
