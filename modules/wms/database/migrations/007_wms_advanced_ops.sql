CREATE TABLE IF NOT EXISTS wms_cycle_counts (
    id                INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    warehouse_id      INT UNSIGNED NOT NULL,
    count_number      VARCHAR(100) NOT NULL,
    count_type        VARCHAR(30) NOT NULL DEFAULT 'full' COMMENT 'full, partial, ad_hoc, abc_a, abc_b, abc_c',
    status            VARCHAR(30) NOT NULL DEFAULT 'open' COMMENT 'open, in_progress, completed, cancelled',
    assigned_to       INT UNSIGNED NULL DEFAULT NULL,
    scheduled_at      DATE NULL DEFAULT NULL,
    completed_at      DATETIME NULL DEFAULT NULL,
    notes             TEXT NULL DEFAULT NULL,
    created_by        INT UNSIGNED NOT NULL,
    created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_wms_cycle_count_number (count_number),
    INDEX idx_wms_cycle_count_warehouse (warehouse_id),
    INDEX idx_wms_cycle_count_status (status),
    INDEX idx_wms_cycle_count_assignee (assigned_to),
    CONSTRAINT fk_wms_cycle_count_warehouse FOREIGN KEY (warehouse_id) REFERENCES wms_warehouses (id) ON DELETE CASCADE,
    CONSTRAINT fk_wms_cycle_count_assignee FOREIGN KEY (assigned_to) REFERENCES wms_users (id) ON DELETE SET NULL,
    CONSTRAINT fk_wms_cycle_count_creator FOREIGN KEY (created_by) REFERENCES wms_users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS wms_cycle_count_items (
    id                INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    cycle_count_id    INT UNSIGNED NOT NULL,
    product_id        INT UNSIGNED NOT NULL,
    location_id       INT UNSIGNED NULL DEFAULT NULL,
    batch_id          INT UNSIGNED NULL DEFAULT NULL,
    expected_qty      DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    counted_qty       DECIMAL(14,4) NULL DEFAULT NULL,
    difference        DECIMAL(14,4) GENERATED ALWAYS AS (COALESCE(counted_qty, 0) - expected_qty) STORED,
    status            VARCHAR(30) NOT NULL DEFAULT 'pending' COMMENT 'pending, counted, resolved',
    notes             TEXT NULL DEFAULT NULL,
    counted_at        DATETIME NULL DEFAULT NULL,
    created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_wms_cycle_count_item_count (cycle_count_id),
    INDEX idx_wms_cycle_count_item_product (product_id),
    INDEX idx_wms_cycle_count_item_location (location_id),
    INDEX idx_wms_cycle_count_item_status (status),
    CONSTRAINT fk_wms_cycle_count_item_count FOREIGN KEY (cycle_count_id) REFERENCES wms_cycle_counts (id) ON DELETE CASCADE,
    CONSTRAINT fk_wms_cycle_count_item_product FOREIGN KEY (product_id) REFERENCES wms_products (id) ON DELETE CASCADE,
    CONSTRAINT fk_wms_cycle_count_item_location FOREIGN KEY (location_id) REFERENCES wms_locations (id) ON DELETE SET NULL,
    CONSTRAINT fk_wms_cycle_count_item_batch FOREIGN KEY (batch_id) REFERENCES wms_batches (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

